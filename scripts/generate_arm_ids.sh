set -euo pipefail

PROGRAM="xxd"
CLANG_FORMAT="${CLANG_FORMAT:-clang-format}"

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"

MODE="write"

if [ "$#" -gt 0 ]; then
    case "$1" in
        --check)
            MODE="check"
            ;;
        -h|--help)
            echo "Usage: $0 [--check]"
            echo "  --check  verify that include/arm_ids.h matches data/arm.ids"
            exit 0
            ;;
        *)
            echo "Error: unknown option: $1" >&2
            exit 2
            ;;
    esac
fi

if ! command -v "$PROGRAM" >/dev/null 2>&1; then
    echo "Error: $PROGRAM not found. Cannot generate arm.ids." >&2
    exit 1
fi

if ! command -v "$CLANG_FORMAT" >/dev/null 2>&1; then
    echo "Error: $CLANG_FORMAT not found. Install clang-format or set CLANG_FORMAT." >&2
    exit 1
fi

cd "$PROJECT_ROOT" || exit 1

IDS_FILE="data/arm.ids"
TARGET="include/arm_ids.h"

emit_header() {
    cat <<'EOF'
/* SPDX-License-Identifier: MIT */

#include <stddef.h>
#include <stdint.h>

#ifndef ARM_IDS_H
#define ARM_IDS_H

/**
 * Auto-generated database of ARM CPU implementer and part IDs.
 *
 * This file contains a pre-compiled byte array representing a text database
 * that maps raw ARM vendor and part hex codes to human-readable processor names
 * (e.g., mapping 0x41/0xd0b to "Cortex-A76").
 *
 * WARNING: Do not edit this file manually. It is generated by scripts/generate_arm_ids.sh
 * to ensure the binary is self-contained without needing external database files at runtime.
 */

EOF
}

generate() {
    emit_header
    "$PROGRAM" -i "$IDS_FILE" | sed \
        -e 's/data_arm_ids/arm_ids/g' \
        -e 's/^unsigned char arm_ids/static const uint8_t arm_ids/' \
        -e 's/^unsigned int arm_ids_len/static const size_t arm_ids_len/'
    printf '\n#endif /* ARM_IDS_H */\n'
}

tmp="$(mktemp ./.arm_ids.XXXXXX.h)"
trap 'rm -f "$tmp"' EXIT

generate > "$tmp"
"$CLANG_FORMAT" -i "$tmp"

if [ "$MODE" = "check" ]; then
    if ! cmp -s "$TARGET" "$tmp"; then
        echo "Error: $TARGET is out of date with $IDS_FILE." >&2
        diff -u "$TARGET" "$tmp" | head -n 40 >&2 || true
        echo "Run 'make arm-ids' and commit the result." >&2
        exit 1
    fi

    echo "$TARGET is up to date."
else
    install -m 644 "$tmp" "$TARGET"
    trap - EXIT
    rm -f "$tmp"
    echo "Generated $TARGET from $IDS_FILE."
fi
